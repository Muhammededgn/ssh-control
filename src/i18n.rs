#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    Tr,
    Es,
    Ru,
}

impl Lang {
    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "EN",
            Lang::Tr => "TR",
            Lang::Es => "ES",
            Lang::Ru => "RU",
        }
    }

    fn from_code(code: &str) -> Option<Self> {
        match code {
            "EN" => Some(Lang::En),
            "TR" => Some(Lang::Tr),
            "ES" => Some(Lang::Es),
            "RU" => Some(Lang::Ru),
            _ => None,
        }
    }

    pub fn strings(self) -> &'static Strings {
        match self {
            Lang::En => &EN,
            Lang::Tr => &TR,
            Lang::Es => &ES,
            Lang::Ru => &RU,
        }
    }

    /// Reads the remembered UI language preference. Defaults to `En` if the
    /// file is missing, unreadable, or holds an unrecognized code — this is a
    /// non-secret convenience file, not the encrypted config, so failures are
    /// never fatal.
    pub fn load_from_file(path: &std::path::Path) -> Self {
        std::fs::read_to_string(path)
            .ok()
            .and_then(|s| Lang::from_code(s.trim()))
            .unwrap_or(Lang::En)
    }

    /// Persists the UI language preference for the next launch. Best-effort:
    /// a failure to write this file should never block or crash the app.
    /// Creates the parent config directory if it doesn't exist yet (e.g. the
    /// language is picked before the master password is ever set).
    pub fn save_to_file(self, path: &std::path::Path) {
        if let Some(parent) = path.parent() {
            let _ = std::fs::create_dir_all(parent);
        }
        let _ = std::fs::write(path, self.code());
    }
}

